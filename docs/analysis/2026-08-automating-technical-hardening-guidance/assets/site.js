  /* --- the current page, marked in the navigation ------------------------
     Was an inline script on three of the eight pages and absent from the other
     seven, so the navigation announced the current page inconsistently. Doing
     it here does it once, for every page. */

  function markCurrentNav() {
    var here = (window.location.pathname.split("/").pop() || "index.html");
    document.querySelectorAll(".site-nav a").forEach(function (a) {
      var target = (a.getAttribute("href") || "").split("/").pop();
      if (target && target === here) a.setAttribute("aria-current", "page");
    });
  }

  /* The site header is sticky and wraps to a different height at different
     widths. Two stylesheet rules need the real number: the toc rail sticks
     below it, and scroll-padding keeps same-page anchors from landing under
     it. CSS carries a close-enough fallback for the moment before this runs
     and for environments without layout. */
  function headerHeight() {
    var h = document.querySelector(".site-header");
    if (!h || !h.offsetHeight) return;
    if (!document.documentElement.style ||
        typeof document.documentElement.style.setProperty !== "function") return;
    document.documentElement.style.setProperty("--header-h", h.offsetHeight + "px");
  }
  /* --- the open questions: <div data-open-questions></div> ---------------
     Four sections, one across all three approaches and one per approach, each
     a list of single-line questions that open into the reasoning behind them.

     The page was twelve sections of prose: a reproduced evidence register, six
     questions each with its own headings and sub-headings, two reproduced
     lists, and blocks on what would settle the disagreement and how to
     contribute. A reader looking for what is unresolved read an essay. This is
     the same content as a list you can scan and open.

     A question reproduced from a source document keeps that document's
     wording, including its errors, and says where it came from. Rewriting
     someone else's question is a way of answering it. */
  function renderOpenQuestions(node) {
    load("questions.json").then(function (d) {
      node.textContent = "";
      if (d.intro) node.appendChild(el("p", "lede", d.intro));
      (d.sections || []).forEach(function (sec, i) {
        var wrap = el("section", "oq");
        wrap.id = "oq-" + sec.key;
        /* Numbered, because every other section heading on this site is and a
           page whose headings are not reads as a different kind of page. */
        wrap.appendChild(el("h2", null, (i + 1) + ". " + sec.label));
        if (sec.intro) {
          var t = el("div", "tier2");
          t.appendChild(el("p", null, sec.intro));
          wrap.appendChild(t);
        }
        sec.questions.forEach(function (q) {
          var det = document.createElement("details");
          det.className = "oq__item";
          det.id = "q-" + q.id;
          var sum = document.createElement("summary");
          sum.appendChild(el("span", "oq__q", q.q));
          if (q.verbatim) sum.appendChild(el("span", "oq__src", "as asked"));
          det.appendChild(sum);
          var body = el("div", "oq__why");
          body.appendChild(el("p", null, q.why));
          if (q.verbatim) {
            body.appendChild(el("p", "oq__from",
              "Reproduced from " + q.verbatim + ", in its own words."));
          }
          det.appendChild(body);
          wrap.appendChild(det);
        });
        node.appendChild(wrap);
      });
    }).catch(function () { fail(node, "questions.json could not be loaded."); });
  }


