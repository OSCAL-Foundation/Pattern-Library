  function initTabs(group) {
    var tabs = Array.prototype.slice.call(group.querySelectorAll('[role="tab"]'));
    /* Look inside the group before the document. A group built by a renderer is
       wired up before it is attached, so getElementById alone found nothing and
       threw, which the renderer's catch reported as a failed load. Searching the
       group first makes the order it is called in stop mattering. */
    function panelFor(t) {
      var id = t.getAttribute("aria-controls");
      var within = group.querySelectorAll('[id="' + id + '"]');
      return (within && within[0]) || document.getElementById(id);
    }
    function select(i) {
      tabs.forEach(function (t, j) {
        var on = i === j;
        t.setAttribute("aria-selected", String(on));
        t.tabIndex = on ? 0 : -1;
        var panel = panelFor(t);
        if (panel) panel.hidden = !on;
      });
    }
    tabs.forEach(function (t, i) {
      t.addEventListener("click", function () { select(i); });
      t.addEventListener("keydown", function (e) {
        var d = e.key === "ArrowRight" ? 1 : e.key === "ArrowLeft" ? -1 : 0;
        if (!d) return;
        e.preventDefault();
        var n = (i + d + tabs.length) % tabs.length;
        tabs[n].focus(); select(n);
      });
    });
    select(0);
  }

