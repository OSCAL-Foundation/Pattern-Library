  /* --- media-type icons -------------------------------------------------------
     Glyphs drawn inline so they inherit currentColor and need no font and no
     request. A file is a page with the type on a filled badge across it, which is
     the one thing that survives at this size: a reader recognises "PDF" faster
     than any pictogram of a page.

     The first drawing lettered the type INSIDE the page outline, which left the
     letters about 11 units wide in a 20 unit box, and at 16px they were a grey
     smudge. Reversing them out of a badge that overhangs the page on both sides
     buys about 70% more width for the same icon, and the badge reads as a shape
     even before the letters resolve.

     The letters are part of the drawing, so the icon is marked aria-hidden and
     the link carries the media type in its title and its label. */

  var MEDIA_ICON = { xml: "XML", pdf: "PDF", json: "JSON" };

  /* Returned as markup, not as created nodes. Every other SVG on this site is
     injected as a string, and namespaced element creation is one of the few DOM
     calls the page-check harness does not implement, so a created <svg> rendered
     nowhere and reported nothing. Markup works in both. */
  var STROKE = 'fill="none" stroke="currentColor" stroke-width="1.4" ' +
               'stroke-linejoin="round" stroke-linecap="round"';

  function mediaIconMarkup(kind) {
    var open = '<svg class="micon micon--' + kind + '" viewBox="0 0 24 24" ' +
               'aria-hidden="true" focusable="false">';
    if (kind === "web") {
      /* A globe: this one is not a file, it is a page on the publisher's site.

         The meridians are a diamond of straight segments rather than two bezier
         curves. They read the same at this size, and they keep the glyph inside
         the subset tools/svgrender.py can rasterise, so the icon can be checked
         by looking at it rather than by trusting it. */
      return open +
        '<circle ' + STROKE + ' cx="12" cy="12" r="8.5"/>' +
        '<path ' + STROKE + ' d="M3.7 9.2h16.6"/>' +
        '<path ' + STROKE + ' d="M3.7 14.8h16.6"/>' +
        '<path ' + STROKE + ' d="M12 3.5L7.8 12L12 20.5L16.2 12Z"/>' +
        "</svg>";
    }
    if (kind === "link") {
      /* An arrow leaving a box: somewhere else, but not necessarily the web. */
      return open +
        '<path ' + STROKE + ' d="M13.5 4h6.5v6.5"/>' +
        '<path ' + STROKE + ' d="M20 4l-9 9"/>' +
        '<path ' + STROKE + ' d="M16 14.5V20H4.5V6.5H10"/>' +
        "</svg>";
    }
    /* A page with a folded corner, and the type reversed out of a badge. */
    return open +
      '<path ' + STROKE + ' d="M5.5 2.7h8l5 5v13.6h-13z"/>' +
      '<path ' + STROKE + ' d="M13.5 2.7v5h5"/>' +
      '<rect class="micon__badge" x="1.6" y="12.4" width="20.8" height="7.6" rx="1.6"/>' +
      '<text class="micon__label" x="12" y="18.2">' +
      escapeHtml(MEDIA_ICON[kind] || "") + "</text></svg>";
  }

